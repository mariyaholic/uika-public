// home.mjs — `uika home status|regen [--apply] [--force] [--json]` (ADR-0051 amendment, 2026-10-20).
// Regenerates the two home-law files that harnesses load outside an adopted repo's AGENTS.md chain:
// DSH's user-global ~/.dsh/AGENTS.md (ADR-0049) and Hermes's ~/.hermes.md (ADR-0047). Until now
// both were hand-written "generated-shaped" copies of the home AGENTS.md, and `uika deploy` could
// only guess staleness from mtimes. The shared sections are now rendered from one source (this
// module + estate.json posture/roster/root); each harness keeps its own face (header, self-edit
// lock list, signing line, estate seams). A trailing fingerprint makes drift and hand edits
// detectable by content, the same way the `uika:docs` blocks do (ADR-0053).
// Dry-run by default. --apply writes, with a timestamped backup of any file it replaces; a file
// that is hand-edited or carries no intact fingerprint (unmanaged) is only overwritten with --force. These files govern agents (self-edit lock): agents run the
// dry run and report; the owner runs --apply.
import { existsSync, readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { homedir } from "node:os";
import { join, dirname } from "node:path";
import { ESTATE } from "./targets.mjs";

const sha12 = (s) => createHash("sha256").update(s).digest("hex").slice(0, 12);
const FP_RE = /^<!-- uika:home (\S+) · generated by `uika home regen` from estate\.json \(ADR-0051\) · sha256:([0-9a-f]{12}) -->$/;
const FP_ANY = /<!-- uika:home \S+ · /;
const fingerprint = (id, hash) => `<!-- uika:home ${id} · generated by \`uika home regen\` from estate.json (ADR-0051) · sha256:${hash} -->`;
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

