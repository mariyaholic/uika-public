function estateOf(root) {
  const e = JSON.parse(readFileSync(join(root, "estate.json"), "utf8")).estate ?? {};
  return {
    mode: e.posture?.mode ?? "near-autopilot",
    lock: e.posture?.selfEditLock ?? "full",
    budget: e.posture?.subagentTurnBudget ?? 15,
    roles: e.roster?.roles ?? ["tower", "scout", "impl", "review", "judge"],
    repo: e.root ?? root,
  };
}

