const lf = (s) => s.replace(/\r\n/g, "\n");

// Classify one existing file against the expected text. Only line endings are forgiven (CRLF reads
// as LF, deliberately); every other byte counts, including the final newline.
//   absent | current | stale (generated and intact, but the expected text moved on — including a
//   lost final newline) | edited (a fingerprint is present but is not the intact last line over its
//   own body: hand edits, or text appended after it) | unmanaged (no fingerprint anywhere: the
//   hand-written pre-generator copy, or a file whose fingerprint was removed)
// Edited and unmanaged files are only replaced with --force.
export function homeFileState(text, expected) {
  if (text == null) return "absent";
  const t = lf(text);
  if (t === expected) return "current";
  const lines = t.replace(/\n+$/, "").split("\n");
  const m = FP_RE.exec(lines.at(-1) ?? "");
  if (!m) return FP_ANY.test(t) ? "edited" : "unmanaged";
  const body = lines.slice(0, -1).join("\n").replace(/\n+$/, "");
  return sha12(body) === m[2] ? "stale" : "edited";
}
export const NEEDS_FORCE = new Set(["edited", "unmanaged"]);

// Backup path that never overwrites an earlier backup: <file>.bak-YYYYMMDD-HHMMSS (local time),
// then -2, -3, ... if that name is taken.
export function backupPath(file, stamp = localStamp()) {
  let p = `${file}.bak-${stamp}`;
  for (let n = 2; existsSync(p); n++) p = `${file}.bak-${stamp}-${n}`;
  return p;
}
function localStamp(d = new Date()) {
  const z = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}${z(d.getMonth() + 1)}${z(d.getDate())}-${z(d.getHours())}${z(d.getMinutes())}${z(d.getSeconds())}`;
}

// Minimal line diff (LCS) for files of a few hundred lines; returns "-"/"+" lines with context.
export function lineDiff(a, b, context = 1) {
  const x = a.split("\n"), y = b.split("\n");
  const n = x.length, m = y.length;
  const L = Array.from({ length: n + 1 }, () => new Int32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) L[i][j] = x[i] === y[j] ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  const ops = [];
  let i = 0, j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && x[i] === y[j]) { ops.push([" ", x[i]]); i++; j++; }
    else if (i < n && (j === m || L[i + 1][j] >= L[i][j + 1])) { ops.push(["-", x[i]]); i++; }
    else { ops.push(["+", y[j]]); j++; }
  }
  const keep = ops.map((o, k) => o[0] !== " " || ops.slice(Math.max(0, k - context), k + context + 1).some((p) => p[0] !== " "));
  const out = [];
  let gap = false;
  ops.forEach((o, k) => { if (keep[k]) { if (gap) out.push("  …"); gap = false; out.push(`${o[0]} ${o[1]}`); } else gap = true; });
  return out;
}

export function homeRegen({ root = ESTATE, home = homedir(), apply = false, force = false, faces = Object.keys(HOME_FACES), emit = console.log, stamp } = {}) {
  const results = [];
  for (const id of faces) {
    const file = HOME_FACES[id].file(home);
    const expected = homeLaw(root, id, { home });
    const text = existsSync(file) ? readFileSync(file, "utf8") : null;
    const state = homeFileState(text, expected);
    const diff = state === "current" ? [] : lineDiff(text == null ? "" : lf(text).replace(/\n$/, ""), expected.replace(/\n$/, ""));
    const r = { id, file, state, added: diff.filter((l) => l.startsWith("+")).length, removed: diff.filter((l) => l.startsWith("-")).length, written: false, backup: null };
    emit(`home ${id}: ${state.toUpperCase()} ${file}${state === "current" ? "" : ` (+${r.added} -${r.removed})`}`);
    if (state !== "current") for (const l of diff) emit(`  ${l}`);
    if (state !== "current" && !r.added && !r.removed) emit("  ~ only the final newline differs");
    if (apply && state !== "current") {
      if (NEEDS_FORCE.has(state) && !force) emit(`  SKIP ${id}: ${state === "edited" ? "hand-edited since generation" : "no intact uika:home fingerprint (unmanaged)"}; re-run with --force to replace it (a backup is kept)`);
      else {
        if (text != null) { r.backup = backupPath(file, stamp); copyFileSync(file, r.backup); }
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, expected);
        r.written = true;
        emit(`  WROTE ${file}${r.backup ? ` (backup ${r.backup})` : ""}`);
      }
    }
    results.push(r);
  }
  if (!apply && results.some((r) => r.state !== "current")) emit(`dry run; add --apply to write${results.some((r) => NEEDS_FORCE.has(r.state)) ? " (--force for edited/unmanaged files)" : ""} — these files govern agents: the owner applies, agents only report`);
  return results;
}

// For `uika deploy`'s law leg: content-based freshness instead of mtimes.
export function homeStates({ root = ESTATE, home = homedir() } = {}) {
  return Object.keys(HOME_FACES).map((id) => {
    const file = HOME_FACES[id].file(home);
    const text = existsSync(file) ? readFileSync(file, "utf8") : null;
    return { id, file, state: homeFileState(text, homeLaw(root, id, { home })) };
  });
}

export async function home({ rest = [], apply = false, force = false, opts = {} }) {
  const sub = rest[0] || "status";
  const root = opts.root ?? ESTATE;
  if (sub === "status") {
    const s = homeStates({ root });
    if (opts.json) console.log(JSON.stringify(s, null, 2));
    else for (const r of s) console.log(`home ${r.id}: ${r.state.toUpperCase()} ${r.file}`);
    return s;
  }
  if (sub === "regen") {
    const lines = [];
    const r = homeRegen({ root, apply, force, emit: opts.json ? (l) => lines.push(l) : console.log });
    if (opts.json) console.log(JSON.stringify({ results: r, log: lines }, null, 2));
    return r;
  }
  throw new Error("usage: home status [--json] | home regen [--apply] [--force] [--json]  (ADR-0051 amendment)");
}
